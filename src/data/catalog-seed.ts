function cakeWeights(
  productId: string,
  skuPrefix: string,
  flavour: string,
  prices: [number, number, number, number],
  compares: [number | null, number | null, number | null, number | null],
) {
  const labels = [
    { name: "500 g", grams: 500, sku: `${skuPrefix}-500` },
    { name: "1 kg", grams: 1000, sku: `${skuPrefix}-1K` },
    { name: "1.5 kg", grams: 1500, sku: `${skuPrefix}-15` },
    { name: "2 kg", grams: 2000, sku: `${skuPrefix}-2K` },
  ];
  return labels.map((row, i) => ({
    id: `${productId}-v${i}`,
    productId,
    sku: row.sku,
    name: row.name,
    flavour,
    weightGrams: row.grams,
    weightLabel: row.name,
    pricePaise: prices[i],
    compareAtPaise: compares[i],
    status: "ACTIVE" as const,
    unlimitedInventory: false,
    minOrderQty: 1,
    maxOrderQty: 4,
    sortOrder: i + 1,
    availableQty: 32,
  }));
}

function singleVariant(
  productId: string,
  sku: string,
  name: string,
  pricePaise: number,
  compareAtPaise: number | null,
  flavour: string | null,
  weightLabel: string,
) {
  return [
    {
      id: `${productId}-v0`,
      productId,
      sku,
      name,
      flavour,
      weightGrams: null,
      weightLabel,
      pricePaise,
      compareAtPaise,
      status: "ACTIVE" as const,
      unlimitedInventory: false,
      minOrderQty: 1,
      maxOrderQty: 12,
      sortOrder: 1,
      availableQty: 24,
    },
  ];
}

function product(
  partial: Omit<CatalogProduct, "status" | "images" | "seoTitle" | "seoDescription" | "thumbnailUrl"> & {
    image: string;
  },
): CatalogProduct {
  const { image, ...rest } = partial;
  return {
    ...rest,
    status: "ACTIVE",
    thumbnailUrl: image,
    seoTitle: `${rest.name} | Clumsy Cheetah`,
    seoDescription: rest.shortDescription,
    images: [
      {
        id: `${rest.id}-img`,
        url: image,
        alt: rest.name,
        sortOrder: 0,
        isPrimary: true,
      },
    ],
  };
}

